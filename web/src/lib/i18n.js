/* Langue du navigateur : « fr » ou « en » (FR par défaut). */
export function detecterLangue(navigatorLike = typeof navigator !== 'undefined' ? navigator : null) {
  const candidates = [...(navigatorLike?.languages ?? []), navigatorLike?.language].filter(Boolean);
  for (const c of candidates) {
    const base = String(c).toLowerCase().slice(0, 2);
    if (LANGS.includes(base)) return base;
  }
  return 'fr';
}

/* Remplace les marqueurs {cle} d'un texte : interpoler('sur {cap}', { cap: '1 800' }). */
export function interpoler(texte, valeurs = {}) {
  return String(texte).replace(/\{(\w+)\}/g, (m, k) => (k in valeurs ? String(valeurs[k]) : m));
}

/* Textes renvoyés par la Semepa (français) : traduits quand on les connaît, laissés tels quels sinon. */
export function libelleAffichage(affichage, t) {
  if (affichage === 'Fermeture temporaire') return t.closed_temp;
  if (affichage === 'COMPLET') return t.card_full;
  return affichage;
}
