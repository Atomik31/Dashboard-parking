/* Langue du navigateur : « fr » ou « en » (FR par défaut). */
export function detecterLangue(navigatorLike = typeof navigator !== 'undefined' ? navigator : null) {
  const candidates = [...(navigatorLike?.languages ?? []), navigatorLike?.language].filter(Boolean);
  for (const c of candidates) {
    const base = String(c).toLowerCase().slice(0, 2);
    if (LANGS.includes(base)) return base;
  }
  return 'fr';
}
